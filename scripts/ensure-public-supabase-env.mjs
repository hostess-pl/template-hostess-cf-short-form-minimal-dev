/**
 * Resolve PUBLIC CMS env and write src/generated/public-cms-env.ts so Astro/Vite
 * can import values (prebuild process.env does not carry into `astro build`).
 *
 * Client hostess deploys must never bake agency template slugs (tpl-*).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return {}
  const out = {}
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i === -1) continue
    const k = t.slice(0, i).trim()
    let v = t.slice(i + 1).trim()
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1)
    }
    out[k] = v
  }
  return out
}

function loadWranglerVars(filePath) {
  if (!existsSync(filePath)) return {}
  try {
    const raw = readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '')
    const parsed = JSON.parse(raw)
    return parsed.vars && typeof parsed.vars === 'object' ? parsed.vars : {}
  } catch {
    return {}
  }
}

function isTemplateCmsSlug(slug) {
  return /^tpl[-_]/i.test(String(slug || '').trim())
}

const root = process.cwd()
const fileEnv = {
  ...loadEnvFile(resolve(root, '../hostesswebs/.env')),
  ...loadEnvFile(resolve(root, '../.env')),
  ...loadEnvFile(resolve(root, '.env')),
}
const wranglerVars = loadWranglerVars(resolve(root, 'wrangler.cms-verify.jsonc'))

const url =
  process.env.PUBLIC_SUPABASE_URL ||
  fileEnv.PUBLIC_SUPABASE_URL ||
  wranglerVars.PUBLIC_SUPABASE_URL ||
  process.env.WF_SUPABASE_URL_HOSTESSWEBS_TEST ||
  fileEnv.WF_SUPABASE_URL_HOSTESSWEBS_TEST ||
  ''

const anon =
  process.env.PUBLIC_SUPABASE_ANON_KEY ||
  fileEnv.PUBLIC_SUPABASE_ANON_KEY ||
  wranglerVars.PUBLIC_SUPABASE_ANON_KEY ||
  ''

function envFlagTrue(value) {
  return ['1', 'true', 'yes'].includes(String(value || '').trim().toLowerCase())
}

const hostingPlan = String(process.env.HOSTING_PLAN || fileEnv.HOSTING_PLAN || '')
  .trim()
  .toLowerCase()

// Client deploys must pass PUBLIC_CMS_SITE_SLUG explicitly (submission id).
// Never fall back to wrangler.cms-verify.jsonc (agency tpl-* demos).
const cmsExplicit =
  hostingPlan === 'pro' ||
  envFlagTrue(process.env.CMS_ENABLED || fileEnv.CMS_ENABLED) ||
  Boolean(String(process.env.PUBLIC_CMS_SITE_SLUG || '').trim())

let slug = ''
if (cmsExplicit) {
  slug = String(process.env.PUBLIC_CMS_SITE_SLUG || '').trim()
  if (!slug && existsSync(resolve(root, 'cms.site.json'))) {
    try {
      slug = JSON.parse(readFileSync(resolve(root, 'cms.site.json'), 'utf8')).siteSlug || ''
    } catch {
      slug = ''
    }
  }
  // Agency CMS-verify demos only: allow wrangler verify slug when not a client deploy.
  const allowVerifyFallback = envFlagTrue(process.env.ALLOW_CMS_VERIFY_SLUG || fileEnv.ALLOW_CMS_VERIFY_SLUG)
  if (!slug && allowVerifyFallback) {
    slug = String(wranglerVars.PUBLIC_CMS_SITE_SLUG || wranglerVars.CMS_SITE_SLUG || '').trim()
  }
  if (!slug) {
    slug = String(fileEnv.PUBLIC_CMS_SITE_SLUG || '').trim()
  }
  if (isTemplateCmsSlug(slug) && !allowVerifyFallback) {
    console.warn(`[env] refusing to bake template CMS slug "${slug}" on client deploy`)
    slug = ''
  }
}

const siteUrl =
  process.env.SITE_URL ||
  fileEnv.SITE_URL ||
  wranglerVars.SITE_URL ||
  ''

if (url) process.env.PUBLIC_SUPABASE_URL = url
if (anon) process.env.PUBLIC_SUPABASE_ANON_KEY = anon
if (slug) {
  process.env.PUBLIC_CMS_SITE_SLUG = slug
  process.env.CMS_SITE_SLUG = slug
} else {
  delete process.env.PUBLIC_CMS_SITE_SLUG
  delete process.env.CMS_SITE_SLUG
}
if (siteUrl) process.env.SITE_URL = siteUrl

const outDir = resolve(root, 'src/generated')
mkdirSync(outDir, { recursive: true })
const outFile = resolve(outDir, 'public-cms-env.ts')
writeFileSync(
  outFile,
  `/* Generated by scripts/ensure-public-supabase-env.mjs — do not edit */\n` +
    `export const GENERATED_PUBLIC_SUPABASE_URL = ${JSON.stringify(url)}\n` +
    `export const GENERATED_PUBLIC_SUPABASE_ANON_KEY = ${JSON.stringify(anon)}\n` +
    `export const GENERATED_PUBLIC_CMS_SITE_SLUG = ${JSON.stringify(slug)}\n` +
    `export const GENERATED_SITE_URL = ${JSON.stringify(siteUrl)}\n`,
)

console.log(`[env] PUBLIC_SUPABASE_URL=${url ? 'set' : 'missing'}`)
console.log(`[env] PUBLIC_SUPABASE_ANON_KEY=${anon ? 'set' : 'missing'}`)
console.log(`[env] PUBLIC_CMS_SITE_SLUG=${slug || '(none)'}`)
console.log(`[env] SITE_URL=${siteUrl || '(none)'}`)
console.log(`[env] wrote ${outFile}`)
